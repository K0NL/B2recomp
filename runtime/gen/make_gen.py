def carr(name, b):
    r = ['static const uint8_t %s[%d] = {' % (name, max(len(b), 1))]
    for i in range(0, len(b), 24):
        r.append('  ' + ','.join(str(x) for x in b[i:i + 24]) + ',')
    r.append('};')
    return r


