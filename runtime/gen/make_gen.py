def elf_layout(path):
    """PT_LOAD segments and DYNAMIC tags of an ELF written by nso2elf (file offset = vaddr + 0x1000)."""
    b = open(path, 'rb').read()
    phoff, = struct.unpack_from('<Q', b, 0x20)
    phentsize, phnum = struct.unpack_from('<HH', b, 0x36)
    loads, dyn = [], None
    for i in range(phnum):
        t, _, off, va, _, fsz, msz = struct.unpack_from('<IIQQQQQ', b, phoff + i * phentsize)
        if t == 1:
            loads.append((off, va, fsz, msz))
        elif t == 2:
            dyn = off
    tags = {}
    while dyn is not None:
        tag, val = struct.unpack_from('<qQ', b, dyn)
        if tag == 0:
            break
        tags.setdefault(tag, val)
        dyn += 16
    return b, loads, tags


def page(x):
    return (x + 0xfff) & ~0xfff


