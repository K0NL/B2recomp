devinfo = []
for p in range(inner[1] + inner[2] + 1):                 # every pname either switch answers
    t = case_target(outer, p)
    w = sdk_ins(t)
    m = mov_imm(w)
    v = -1
    if m and m[1] == 0:
        v = m[0]                                         # the case returns a fixed number
    elif (w & 0xffc003ff) == 0xb94003e0:                 # ldr w0, [sp, #..]: what the getter stored (0 = not answered)
        i = p - inner[1]
        if i < 0 or i > inner[2]:
            v = 0
        else:
            t2 = case_target(inner, p)
            m2 = mov_imm(sdk_ins(t2))
            v = m2[0] if m2 else (0 if sdk_ins(t2) == 0xd65f03c0 else -1)
    devinfo.append(v)
