"""Generates quad_tests.h: test vectors for the binary128 soft-float in nnlibc2.c.
Results are computed here with exact rational arithmetic (fractions.Fraction) and rounded to nearest-even,
independently of the C implementation."""
import random, struct
from fractions import Fraction
BIAS, P = 16383, 113
EMIN = 1 - BIAS

def decode(bits):
    s = bits >> 127; e = (bits >> 112) & 0x7fff; f = bits & ((1 << 112) - 1)
    if e == 0x7fff: return ('nan' if f else 'inf', s)
    if e == 0: return (Fraction(f) * Fraction(2) ** (EMIN - 112) * (-1 if s else 1), s)
    return (Fraction((1 << 112) | f) * Fraction(2) ** (e - BIAS - 112) * (-1 if s else 1), s)

def encode(v, sign_if_zero=0, p=P, bias=BIAS, ebits=15):
    """round-to-nearest-even encoding of an exact rational"""
    emax = (1 << ebits) - 1
    if v == 0: return sign_if_zero << (p - 1 + ebits)
    s = 1 if v < 0 else 0
    a = -v if s else v
    # exponent e such that 2^e <= a < 2^(e+1)
    e = a.numerator.bit_length() - a.denominator.bit_length()
    if Fraction(2) ** e > a: e -= 1
    if Fraction(2) ** (e + 1) <= a: e += 1
    emin = 1 - bias
    if e < emin: e = emin
    q = a / Fraction(2) ** (e - (p - 1))            # significand as a rational, target p bits
    n = q.numerator // q.denominator
    r = q - n
    if r > Fraction(1, 2) or (r == Fraction(1, 2) and (n & 1)): n += 1
    if n >> p: n >>= 1; e += 1
    if n >> (p - 1) == 0: be = 0                    # subnormal
    else: be = e + bias
    if be >= emax: return (s << (p - 1 + ebits)) | (emax << (p - 1))
    return (s << (p - 1 + ebits)) | (be << (p - 1)) | (n & ((1 << (p - 1)) - 1))

def rnd():
    k = random.random()
    s = random.getrandbits(1) << 127
    if k < 0.08: return s | random.choice([0, 1, (1 << 112) - 1, 1 << 112, (0x7ffe << 112) | ((1 << 112) - 1), 0x3fff << 112, 0x7fff << 112])
    if k < 0.20: return s | random.getrandbits(112)                                   # subnormal
    if k < 0.30: return s | (random.randrange(1, 40) << 112) | random.getrandbits(112)  # near the bottom
    if k < 0.38: return s | (random.randrange(0x7fc0, 0x7fff) << 112) | random.getrandbits(112)
    f = random.getrandbits(112)
    if random.random() < 0.3: f &= ~((1 << random.randrange(1, 112)) - 1)             # short significands: exact ties happen
    return s | (random.randrange(0x3fff - 130, 0x3fff + 130) << 112) | f

QNAN = (0x7fff << 112) | (1 << 111)
INF = 0x7fff << 112
def op(kind, a, b):
    (va, sa), (vb, sb) = decode(a), decode(b)
    if va == 'nan' or vb == 'nan': return None
    if kind == 'sub': b ^= 1 << 127; (vb, sb) = decode(b); kind = 'add'
    if kind == 'add':
        if va == 'inf': return None if vb == 'inf' and sa != sb else a
        if vb == 'inf': return b
        r = va + vb
        return encode(r, sa if (va == 0 and vb == 0 and sa == sb) else 0)
    if kind == 'mul':
        s = sa ^ sb
        if va == 'inf' or vb == 'inf': return None if (va == 0 or vb == 0) else (s << 127) | INF
        return encode(va * vb, s)
    if kind == 'div':
        s = sa ^ sb
        if va == 'inf': return None if vb == 'inf' else (s << 127) | INF
        if vb == 'inf': return s << 127
        if vb == 0: return None if va == 0 else (s << 127) | INF
        return encode(va / vb, s)

random.seed(20261008)
out = ['/* generated by gen_quad_tests.py: do not edit */',
       'typedef struct { int op; uint64_t a[2], b[2], r[2]; } QuadVec;   /* op: 0 add 1 sub 2 mul 3 div; words are {low, high} */',
       'static const QuadVec quad_vecs[] = {']
h = lambda v: '{0x%016xull, 0x%016xull}' % (v & (2**64 - 1), v >> 64)
n = 0
for kind_i, kind in enumerate(['add', 'sub', 'mul', 'div']):
    made = 0
    while made < 150:
        a, b = rnd(), rnd()
        if kind in ('add', 'sub') and random.random() < 0.5:        # close exponents: cancellation and carries
            b = (b & ~(0x7fff << 112)) | (min(0x7ffe, max(0, ((a >> 112) & 0x7fff) + random.randrange(-3, 4))) << 112)
        r = op(kind, a, b)
        if r is None: r = QNAN
        out.append('    {%d, %s, %s, %s},' % (kind_i, h(a), h(b), h(r)))
        made += 1; n += 1
out.append('};')
# conversions
out.append('typedef struct { uint64_t q[2]; uint64_t d; uint32_t f; int64_t i; } QuadConv;   /* quad -> double bits, float bits, int64 (truncated) */')
out.append('static const QuadConv quad_convs[] = {')
for i in range(200):
    q = rnd()
    v, s = decode(q)
    if v in ('nan',): continue
    if v == 'inf':
        d = (s << 63) | (0x7ff << 52); f = (s << 31) | (0xff << 23); iv = -2**63 if s else 2**63 - 1
    else:
        d = encode(v, s, 53, 1023, 11); f = encode(v, s, 24, 127, 8)
        t = abs(v.numerator) // v.denominator
        iv = -t if v < 0 else t
        iv = max(-2**63, min(2**63 - 1, iv))
    out.append('    {%s, 0x%016xull, 0x%08xu, %s},' % (h(q), d, f, ('(-9223372036854775807ll - 1)' if iv == -2**63 else '%dll' % iv)))
out.append('};')
out.append('typedef struct { int64_t i; uint64_t q[2]; uint64_t d; uint64_t dq[2]; } QuadFrom;   /* int64 -> quad, double (as bits) -> quad */')
out.append('static const QuadFrom quad_froms[] = {')
for i in range(120):
    iv = random.choice([0, 1, -1, 2**63 - 1, -2**63, random.getrandbits(64) - 2**63, random.getrandbits(20), -random.getrandbits(40)])
    dbits = random.choice([0, 1 << 63, 1, random.getrandbits(52), random.getrandbits(64) & ~(0x7ff << 52) | (random.randrange(1, 0x7ff) << 52), 0x7ff << 52])
    de = (dbits >> 52) & 0x7ff; df = dbits & ((1 << 52) - 1); ds = dbits >> 63
    if de == 0x7ff: dq = (ds << 127) | INF
    else:
        dv = Fraction(df if de == 0 else df | (1 << 52)) * Fraction(2) ** ((1 if de == 0 else de) - 1075)
        dq = encode(-dv if ds else dv, ds)
    out.append('    {%s, %s, %s, %s},' % (('(-9223372036854775807ll - 1)' if iv == -2**63 else '%dll' % iv), h(encode(Fraction(iv))),
                                       '0x%016xull' % dbits, h(dq)))
out.append('};')
open('quad_tests.h', 'w').write('\n'.join(out) + '\n')
print('wrote quad_tests.h: %d arithmetic vectors' % n)
